export const getBlogs = () => {
  return mockBlogs || [];
};

export const getBlogById = (id) => {
  if (!id) return null;
  return mockBlogs.find(blog => blog.id === id) || null;
};

export const getBlogBySlug = (slug) => {
  if (!slug) return null;
  return mockBlogs.find(blog => blog.slug === slug) || null;
};

export const getBlogCategories = () => {
  if (!mockBlogs || !Array.isArray(mockBlogs)) return [];
  const categories = new Set(mockBlogs.map(blog => blog?.category).filter(Boolean));
  return Array.from(categories);
};

export const getEntityTypes = () => {
  if (!mockBlogs || !Array.isArray(mockBlogs)) return [];
  const types = new Set(mockBlogs.map(blog => blog?.author?.type).filter(Boolean));
  return Array.from(types);
};